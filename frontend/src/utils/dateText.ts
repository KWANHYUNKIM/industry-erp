/**
 * 화면에 <b>찍는</b> 날짜. 원본은 어디서나 <b>2026/07/16</b> 꼴이다(사본 실측 — 눈에 보이는
 * 날짜 413군데가 전부 이 모양이고, 2026-07-16 은 JSON payload 안에서만 나온다).
 *
 * <p>우리는 서버가 주는 ISO 문자열을 그대로 찍는 자리가 <b>표 안에만 158군데</b> 있었다.
 * 한 화면 안에서도 어떤 칸은 슬래시, 어떤 칸은 하이픈이라 같은 날짜가 두 모양으로 보였다.
 *
 * <p>날짜 <b>앞머리만</b> 바꾼다 — 뒤에 시각이 붙어 있으면(2026-07-16T09:30) 그 부분은
 * 건드리지 않는다. 값이 없으면 빈 글자다(호출부에서 || '-' 로 받쳐 쓴다).
 *
 * <p>입력 칸(<input type="date">)에는 쓰지 마세요. 그쪽은 ISO 라야 브라우저가 알아듣는다.
 */
export const dateText = (v?: string | null) =>
  (v ?? '').replace(/^(\d{4})-(\d{2})-(\d{2})/, '$1/$2/$3')
