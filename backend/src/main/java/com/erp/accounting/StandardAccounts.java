    /** @param flags 원본 표시 — [G 묶음] + 대차(D/C) + 계정종류 + 평가구분(0 · t 평가계정대상 · v 평가계정) + 사용(Y/N). */
    private static Spec build(boolean req, String code, String name, AccountDivision d, String detail, String parent, String flags) {
        boolean group = flags.startsWith("G");
        String f = group ? flags.substring(1) : flags;
        AccountEvalKind ev = f.charAt(2) == 't' ? AccountEvalKind.TARGET : f.charAt(2) == 'v' ? AccountEvalKind.EVAL : AccountEvalKind.NONE;
        return new Spec(code, name, d, detail, req, group, group || f.charAt(3) == 'Y', parent,
                f.charAt(0) == 'D' ? AccountDebitCredit.DEBIT : AccountDebitCredit.CREDIT, ev);
    }

    private static Spec a(String code, String name, AccountDivision d, String detail, String parent, String flags) {
        return build(false, code, name, d, detail, parent, flags);
    }

    /** 코드가 직접 찾아 쓰는 계정. 새 회사에 없으면 해당 기능이 곧바로 막힌다. */
    private static Spec req(String code, String name, AccountDivision d, String detail, String parent, String flags) {
        return build(true, code, name, d, detail, parent, flags);
    }

