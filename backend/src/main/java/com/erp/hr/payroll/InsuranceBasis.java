package com.erp.hr.payroll;

/**
 * 원본 사원등록 [기타설정] 건강보험 · 고용보험 칸 — '보수월액기준 / 자동계산 / 안함'.
 *
 * <p>2026-10-13 loginaa 실측: '보수월액기준' 에 보수월액(3,000,000 · 2,000,000)을 넣고 급여를 전체계산하면
 * 그 보험 공제 칸이 <b>빈다</b>(자동계산이면 145,160 · 36,340). 원본은 보수월액기준 사원의 보험료를
 * 급여계산이 셈하지 않는다 — 우리도 같게 줄을 만들지 않는다.
 * 국민연금은 '기준소득월액기준 / 안함' 둘뿐이라 {@link InsuranceCalc} 를 그대로 쓴다.
 */
public enum InsuranceBasis {
    /** 보수월액기준 — 급여계산이 그 보험료를 셈하지 않는다(원본 실측) */
    BASE,
    /** 자동계산 — 과세급여(비과세 수당 제외)에 요율 */
    AUTO,
    /** 안함 — 그 보험 공제 줄을 만들지 않는다 */
    NONE
}
