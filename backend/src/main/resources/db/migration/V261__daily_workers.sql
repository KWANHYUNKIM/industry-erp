-- 일용근로 사원등록(원본 E020105): 상용 사원과 다른 일용근로 사원 목록 · 번호(00001 …).
CREATE TABLE public.daily_workers (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           timestamp(6) without time zone,
    updated_at           timestamp(6) without time zone,
    code                 varchar(20)  NOT NULL,
    name                 varchar(50)  NOT NULL,
    foreigner            boolean      NOT NULL DEFAULT false,
    nationality          varchar(50),
    department_id        bigint,
    mobile               varchar(30),
    email                varchar(100),
    hire_date            date,
    resign_date          date,
    zipcode              varchar(10),
    address              varchar(300),
    employment_insurance boolean      NOT NULL DEFAULT true,
    pension_auto         boolean      NOT NULL DEFAULT false,
    pension_base         numeric(15,0),
    health_auto          boolean      NOT NULL DEFAULT false,
    health_base          numeric(15,0),
    bank_name            varchar(50),
    account_no           varchar(50),
    account_holder       varchar(50),
    remark               varchar(500),
    daily_wage           numeric(15,0),
    fixed_income_tax     numeric(15,0),
    fixed_local_tax      numeric(15,0),
    CONSTRAINT uk_daily_workers_code UNIQUE (code),
    CONSTRAINT fk_daily_workers_department_id FOREIGN KEY (department_id) REFERENCES public.departments(id)
);
CREATE INDEX idx_daily_workers_department_id ON public.daily_workers (department_id);
