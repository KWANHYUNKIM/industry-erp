CREATE TABLE multi_slips (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board      varchar(30) NOT NULL CHECK (board IN ('MULTI_INPUT', 'SALES_CONTRACT', 'BOND_COLLECT', 'MONTHLY_ATTENDANCE')),
    slip_date  date        NOT NULL,
    slip_no    integer     NOT NULL,
    status     varchar(20) NOT NULL CHECK (status IN ('IN_PROGRESS', 'DONE')),
    created_at timestamp,
    updated_at timestamp,
    CONSTRAINT uk_multi_slips_board_date_no UNIQUE (board, slip_date, slip_no)
);

CREATE TABLE multi_slip_lines (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slip_id bigint  NOT NULL REFERENCES multi_slips (id) ON DELETE CASCADE,
    line_no integer NOT NULL,
    fields  jsonb   NOT NULL
);

CREATE INDEX idx_multi_slip_lines_slip_id ON multi_slip_lines (slip_id);
