-- 특별단가등록(E040124)을 원본 모델로 — '특별단가그룹' 마스터 + 그룹에 붙는 거래처 · 창고 · 품목 · 품목그룹.
--
-- 예전: special_prices 한 줄 = (판매/구매, 품목, 거래처 또는 그룹 이름 글자, 단가). 그룹 마스터가 없어 이름이 화면 코드에 박혀 있었다.
-- 원본(2026-10-14 loginaa 실측):
--   특별단가그룹(코드 · 이름) → [거래처설정] 구분(영업 · 구매) · 거래처 / [창고설정] 구분 · 창고
--   [품목별] 그룹 × 품목 = 적용단가 · VAT포함 ('이미 특별단가그룹에 존재하는 코드입니다.' — 한 그룹에 품목 한 번)
--   [품목그룹별] 그룹 × 품목그룹 = 단가기준(출고단가 …) · 조정_비율(%) · 조정_단위처리(소수0자리미만 · 반올림)
-- 거래처의 영업 · 구매 단가그룹은 거래처 칸(business_partners.sales_price_group · purchase_price_group)에 그룹 <b>코드</b>로 든다
-- (원본 거래처추가 창: 영업단가그룹 · 구매단가그룹 체크칸 — 거래처 하나에 영업 그룹 하나 · 구매 그룹 하나).
--
-- 옛 자료는 지우지 않고 옮긴다:
--   · 그룹 이름 글자(거래처 칸 · 옛 단가 줄) → 그룹 하나씩(코드 G0001 …). 같은 이름이 영업 · 구매 양쪽에 쓰였으면 구매 쪽은 '이름(구매)' 로 따로.
--   · 거래처 지정 단가 → 그 거래처 전용 그룹(코드 P0001 …, 이름 '<거래처명> 특별단가') 을 짓고 거래처를 그 그룹에 붙인다.
--     그 거래처가 원래 들던 그룹의 단가도 함께 옮겨(거래처 지정 단가가 앞) 걸리는 값이 예전과 같다.

CREATE TABLE special_price_groups (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6),
    updated_at timestamp(6),
    code       varchar(20)  NOT NULL,
    name       varchar(100) NOT NULL,
    active     boolean      NOT NULL DEFAULT true,
    created_by varchar(50),
    CONSTRAINT uk_special_price_groups_code UNIQUE (code)
);

-- 이름 글자 그룹: (구분, 이름) → 코드
CREATE TEMP TABLE sp_name_map (kind varchar(20), name varchar(50), code varchar(20), gname varchar(100)) ON COMMIT DROP;
INSERT INTO sp_name_map (kind, name)
SELECT DISTINCT 'SALES', trim(sales_price_group) FROM business_partners WHERE nullif(trim(sales_price_group), '') IS NOT NULL
UNION
SELECT DISTINCT 'PURCHASE', trim(purchase_price_group) FROM business_partners WHERE nullif(trim(purchase_price_group), '') IS NOT NULL
UNION
SELECT DISTINCT trade_type, trim(price_group) FROM special_prices WHERE partner_id IS NULL AND nullif(trim(price_group), '') IS NOT NULL;

UPDATE sp_name_map m SET code = 'G' || lpad(x.rn::text, 4, '0')
FROM (SELECT kind, name, row_number() OVER (ORDER BY kind DESC, name) AS rn FROM sp_name_map) x
WHERE x.kind = m.kind AND x.name = m.name;
UPDATE sp_name_map m SET gname = CASE
    WHEN m.kind = 'PURCHASE' AND EXISTS (SELECT 1 FROM sp_name_map s WHERE s.kind = 'SALES' AND s.name = m.name)
        THEN m.name || '(구매)'
    ELSE m.name END;

-- 거래처 지정 단가: (구분, 거래처) → 전용 그룹
CREATE TEMP TABLE sp_partner_map (kind varchar(20), partner_id bigint, code varchar(20), gname varchar(100)) ON COMMIT DROP;
INSERT INTO sp_partner_map (kind, partner_id)
SELECT DISTINCT trade_type, partner_id FROM special_prices WHERE partner_id IS NOT NULL;
UPDATE sp_partner_map m SET code = 'P' || lpad(x.rn::text, 4, '0')
FROM (SELECT kind, partner_id, row_number() OVER (ORDER BY kind DESC, partner_id) AS rn FROM sp_partner_map) x
WHERE x.kind = m.kind AND x.partner_id = m.partner_id;
UPDATE sp_partner_map m SET gname = left(bp.name, 80) || ' 특별단가' || CASE WHEN m.kind = 'PURCHASE' THEN '(구매)' ELSE '' END
FROM business_partners bp WHERE bp.id = m.partner_id;

INSERT INTO special_price_groups (created_at, updated_at, code, name, active)
SELECT now(), now(), code, gname, true FROM sp_name_map
UNION ALL
SELECT now(), now(), code, gname, true FROM sp_partner_map;

-- 단가 표를 새 꼴로: 옛 줄을 임시로 받아 두고 표를 다시 짓는다
CREATE TEMP TABLE sp_old ON COMMIT DROP AS SELECT * FROM special_prices;
DROP TABLE special_prices;

CREATE TABLE special_prices (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    group_id     bigint         NOT NULL REFERENCES special_price_groups (id),
    item_id      bigint         NOT NULL REFERENCES items (id),
    unit_price   numeric(18, 2) NOT NULL DEFAULT 0,
    vat_included boolean        NOT NULL DEFAULT false,
    active       boolean        NOT NULL DEFAULT true,
    remark       varchar(300),
    created_by   varchar(50),
    CONSTRAINT uk_special_prices_group_item UNIQUE (group_id, item_id)
);

-- 그룹 이름 줄(같은 그룹 · 품목이 여럿이면 예전 해석처럼 사용 중 · 최신 하나)
INSERT INTO special_prices (created_at, updated_at, group_id, item_id, unit_price, active, remark, created_by)
SELECT DISTINCT ON (g.id, o.item_id) o.created_at, o.updated_at, g.id, o.item_id, o.unit_price, o.active, o.remark, o.created_by
FROM sp_old o
JOIN sp_name_map m ON m.kind = o.trade_type AND m.name = trim(o.price_group)
JOIN special_price_groups g ON g.code = m.code
WHERE o.partner_id IS NULL
ORDER BY g.id, o.item_id, o.active DESC, o.id DESC;

-- 거래처 지정 줄 → 전용 그룹
INSERT INTO special_prices (created_at, updated_at, group_id, item_id, unit_price, active, remark, created_by)
SELECT DISTINCT ON (g.id, o.item_id) o.created_at, o.updated_at, g.id, o.item_id, o.unit_price, o.active, o.remark, o.created_by
FROM sp_old o
JOIN sp_partner_map pm ON pm.kind = o.trade_type AND pm.partner_id = o.partner_id
JOIN special_price_groups g ON g.code = pm.code
ORDER BY g.id, o.item_id, o.active DESC, o.id DESC;

-- 전용 그룹에 그 거래처가 원래 들던 그룹의 단가도 — 거래처 지정 단가가 없는 품목만(예전 해석: 거래처 지정 → 거래처 그룹)
INSERT INTO special_prices (created_at, updated_at, group_id, item_id, unit_price, vat_included, active, remark, created_by)
SELECT sp.created_at, sp.updated_at, pg.id, sp.item_id, sp.unit_price, sp.vat_included, sp.active, sp.remark, sp.created_by
FROM sp_partner_map pm
JOIN special_price_groups pg ON pg.code = pm.code
JOIN business_partners bp ON bp.id = pm.partner_id
JOIN sp_name_map m ON m.kind = pm.kind
    AND m.name = trim(CASE WHEN pm.kind = 'SALES' THEN bp.sales_price_group ELSE bp.purchase_price_group END)
JOIN special_price_groups og ON og.code = m.code
JOIN special_prices sp ON sp.group_id = og.id
ON CONFLICT (group_id, item_id) DO NOTHING;

-- 거래처 칸: 이름 글자 → 그룹 코드, 거래처 지정 단가가 있던 거래처는 전용 그룹
UPDATE business_partners SET sales_price_group = NULL WHERE trim(sales_price_group) = '';
UPDATE business_partners SET purchase_price_group = NULL WHERE trim(purchase_price_group) = '';
UPDATE business_partners bp SET sales_price_group = m.code
FROM sp_name_map m WHERE m.kind = 'SALES' AND m.name = trim(bp.sales_price_group);
UPDATE business_partners bp SET purchase_price_group = m.code
FROM sp_name_map m WHERE m.kind = 'PURCHASE' AND m.name = trim(bp.purchase_price_group);
UPDATE business_partners bp SET sales_price_group = pm.code
FROM sp_partner_map pm WHERE pm.kind = 'SALES' AND pm.partner_id = bp.id;
UPDATE business_partners bp SET purchase_price_group = pm.code
FROM sp_partner_map pm WHERE pm.kind = 'PURCHASE' AND pm.partner_id = bp.id;

ALTER TABLE business_partners ADD CONSTRAINT fk_business_partners_sales_price_group
    FOREIGN KEY (sales_price_group) REFERENCES special_price_groups (code) ON UPDATE CASCADE;
ALTER TABLE business_partners ADD CONSTRAINT fk_business_partners_purchase_price_group
    FOREIGN KEY (purchase_price_group) REFERENCES special_price_groups (code) ON UPDATE CASCADE;

-- [창고설정] 구분(영업 · 구매) · 창고 — 창고 하나에 구분마다 그룹 하나
CREATE TABLE special_price_group_warehouses (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    group_id     bigint      NOT NULL REFERENCES special_price_groups (id),
    warehouse_id bigint      NOT NULL REFERENCES warehouses (id),
    trade_type   varchar(20) NOT NULL,
    CONSTRAINT uk_special_price_group_warehouses UNIQUE (warehouse_id, trade_type)
);

-- [품목그룹별] 그룹 × 품목그룹 = 단가기준 × (100 + 조정_비율) / 100, 조정_단위처리
CREATE TABLE special_price_item_groups (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    group_id      bigint        NOT NULL REFERENCES special_price_groups (id),
    item_group_id bigint        NOT NULL REFERENCES item_groups (id),
    price_basis   varchar(20)   NOT NULL,
    adjust_rate   numeric(9, 4) NOT NULL DEFAULT 0,
    round_unit    varchar(20)   NOT NULL,
    round_mode    varchar(10)   NOT NULL,
    active        boolean       NOT NULL DEFAULT true,
    created_by    varchar(50),
    CONSTRAINT uk_special_price_item_groups UNIQUE (group_id, item_group_id)
);

-- FK 컬럼 인덱스(맨 앞 칸이 FK 인 UNIQUE 는 그 인덱스를 겸한다: special_prices.group_id · special_price_item_groups.group_id)
CREATE INDEX idx_special_prices_item_id ON special_prices (item_id);
CREATE INDEX idx_business_partners_sales_price_group ON business_partners (sales_price_group);
CREATE INDEX idx_business_partners_purchase_price_group ON business_partners (purchase_price_group);
CREATE INDEX idx_special_price_group_warehouses_group_id ON special_price_group_warehouses (group_id);
CREATE INDEX idx_special_price_item_groups_item_group_id ON special_price_item_groups (item_group_id);
