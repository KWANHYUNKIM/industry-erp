-- (plans/재고1/E040221.md, 2026-10-20 loginaa 실측). 판매/주문 → 출하지시서 → 출하. 미출하 잔량은 출하지시서 줄 기준.
-- 기존 shipments 는 그대로 '출하' 다(이관하지 않는다 — 옛 READY 줄을 지시서로 베끼면 같은 물건이 두 전표로 잡힌다).

CREATE TABLE shipment_orders (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6) without time zone,
    updated_at    timestamp(6) without time zone,
    order_no      varchar(30)  NOT NULL,
    order_date    date         NOT NULL,
    partner_id    bigint       NOT NULL,
    employee_id   bigint,
    warehouse_id  bigint,
    project_id    bigint,
    contact       varchar(50),
    due_date      date,
    postal_code   varchar(10),
    address       varchar(255),
    remark        varchar(500),
    status        varchar(20)  NOT NULL,
    total_quantity numeric(18,2) NOT NULL,
    created_by    varchar(50),
    CONSTRAINT uk_shipment_orders_order_no UNIQUE (order_no),
    CONSTRAINT shipment_orders_status_check CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT fk_shipment_orders_partner_id FOREIGN KEY (partner_id) REFERENCES business_partners (id),
    CONSTRAINT fk_shipment_orders_employee_id FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT fk_shipment_orders_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES warehouses (id),
    CONSTRAINT fk_shipment_orders_project_id FOREIGN KEY (project_id) REFERENCES projects (id)
);
CREATE INDEX idx_shipment_orders_partner_id ON shipment_orders (partner_id);
CREATE INDEX idx_shipment_orders_employee_id ON shipment_orders (employee_id);
CREATE INDEX idx_shipment_orders_warehouse_id ON shipment_orders (warehouse_id);
CREATE INDEX idx_shipment_orders_project_id ON shipment_orders (project_id);
CREATE INDEX idx_shipment_orders_order_date ON shipment_orders (order_date);

CREATE TABLE shipment_order_lines (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_order_id bigint        NOT NULL,
    item_id           bigint        NOT NULL,
    quantity          numeric(18,2) NOT NULL,
    remark            varchar(255),
    CONSTRAINT fk_shipment_order_lines_order_id FOREIGN KEY (shipment_order_id) REFERENCES shipment_orders (id),
    CONSTRAINT fk_shipment_order_lines_item_id FOREIGN KEY (item_id) REFERENCES items (id)
);
CREATE INDEX idx_shipment_order_lines_order_id ON shipment_order_lines (shipment_order_id);
CREATE INDEX idx_shipment_order_lines_item_id ON shipment_order_lines (item_id);

-- 출하 줄 → 출하지시서 줄. 원본은 출하가 이어진 출하지시서도 지워진다(출하는 남는다) — 그래서 SET NULL.
ALTER TABLE shipment_lines ADD COLUMN shipment_order_line_id bigint;
ALTER TABLE shipment_lines ADD CONSTRAINT fk_shipment_lines_shipment_order_line_id
    FOREIGN KEY (shipment_order_line_id) REFERENCES shipment_order_lines (id) ON DELETE SET NULL;
CREATE INDEX idx_shipment_lines_shipment_order_line_id ON shipment_lines (shipment_order_line_id);
