-- 감가상각계산 = 기간 묶음(원본 E010616, 2026-10-22 실측): 신규(회계기수 · 감가상각기간) → 전체계산(대장에 자동 반영) →
-- 조회 · 반영내용삭제 → 고정자산대장에반영 · 삭제 → 기타 전표생성 · 이력. 건수 · 총액은 계산 때 적어 두고,
-- 반영내용을 지워도 남는다. 상각 행(depreciations)이 어느 묶음에서 나왔는지 calc_id 로 단다.
CREATE TABLE depreciation_calcs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      timestamp(6) without time zone,
    updated_at      timestamp(6) without time zone,
    fiscal_term     integer NOT NULL,
    period_from     varchar(7) NOT NULL,
    period_to       varchar(7) NOT NULL,
    reflected       boolean NOT NULL,
    item_count      integer NOT NULL,
    total_amount    numeric(18, 2) NOT NULL,
    excluded_months integer NOT NULL,
    created_by      varchar(50)
);
ALTER TABLE depreciations ADD COLUMN calc_id bigint CONSTRAINT fk_depreciations_calc_id REFERENCES depreciation_calcs (id);
CREATE INDEX idx_depreciations_calc_id ON depreciations (calc_id);
