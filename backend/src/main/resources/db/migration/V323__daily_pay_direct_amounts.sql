CREATE TABLE public.daily_pay_direct_amounts (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ledger_id       bigint        NOT NULL,
    daily_worker_id bigint        NOT NULL,
    day_amount      numeric(15,0),
    memo            varchar(200),
    top_message     varchar(200),
    bottom_message  varchar(200),
    CONSTRAINT fk_daily_pay_direct_amounts_ledger_id FOREIGN KEY (ledger_id) REFERENCES public.daily_pay_ledgers(id),
    CONSTRAINT fk_daily_pay_direct_amounts_daily_worker_id FOREIGN KEY (daily_worker_id) REFERENCES public.daily_workers(id),
    CONSTRAINT uk_daily_pay_direct_amounts UNIQUE (ledger_id, daily_worker_id)
);
CREATE INDEX idx_daily_pay_direct_amounts_daily_worker_id ON public.daily_pay_direct_amounts (daily_worker_id);
