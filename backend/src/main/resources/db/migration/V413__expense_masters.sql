-- 가지급금정산서(회계전표)를 가리킬 칸. 옛 비용 자료는 계정만 있어 비용 마스터로 옮길 수 없다 — 새 칸은 모두 비워 둔다.

CREATE TABLE expense_control_types (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6) without time zone,
    updated_at    timestamp(6) without time zone,
    code          varchar(20)  NOT NULL,
    name          varchar(100) NOT NULL,
    period_type   varchar(20)  NOT NULL,
    person_control boolean     NOT NULL,
    limit_type    varchar(20)  NOT NULL,
    notice_type   varchar(20)  NOT NULL,
    remark        varchar(500),
    active        boolean      NOT NULL,
    CONSTRAINT uk_expense_control_types_code UNIQUE (code),
    CONSTRAINT ck_expense_control_types_period_type CHECK (period_type IN ('DESIGNATED', 'DAILY', 'WEEKLY', 'MONTHLY', 'YEARLY', 'EACH')),
    CONSTRAINT ck_expense_control_types_limit_type CHECK (limit_type IN ('PERSONAL_SAME', 'PERSONAL_EACH', 'TOTAL')),
    CONSTRAINT ck_expense_control_types_notice_type CHECK (notice_type IN ('NONE', 'WARN', 'BLOCK'))
);

CREATE TABLE expense_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      timestamp(6) without time zone,
    updated_at      timestamp(6) without time zone,
    code            varchar(20)   NOT NULL,
    name            varchar(100)  NOT NULL,
    account_id      bigint,
    control_type_id bigint,
    limit_amount    numeric(18,2),
    remark          varchar(500),
    active          boolean       NOT NULL,
    CONSTRAINT uk_expense_items_code UNIQUE (code),
    CONSTRAINT fk_expense_items_account_id FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT fk_expense_items_control_type_id FOREIGN KEY (control_type_id) REFERENCES expense_control_types (id)
);
CREATE INDEX idx_expense_items_account_id ON expense_items (account_id);
CREATE INDEX idx_expense_items_control_type_id ON expense_items (control_type_id);

-- 비용등록 [사용인원](사원 여럿)
CREATE TABLE expense_item_users (
    expense_item_id bigint NOT NULL,
    employee_id     bigint NOT NULL,
    CONSTRAINT pk_expense_item_users PRIMARY KEY (expense_item_id, employee_id),
    CONSTRAINT fk_expense_item_users_item FOREIGN KEY (expense_item_id) REFERENCES expense_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_expense_item_users_employee FOREIGN KEY (employee_id) REFERENCES employees (id)
);
CREATE INDEX idx_expense_item_users_employee_id ON expense_item_users (employee_id);

CREATE TABLE expense_groups (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      timestamp(6) without time zone,
    updated_at      timestamp(6) without time zone,
    code            varchar(20)  NOT NULL,
    name            varchar(100) NOT NULL,
    control_type_id bigint,
    add_input       boolean      NOT NULL,
    remark          varchar(500),
    active          boolean      NOT NULL,
    CONSTRAINT uk_expense_groups_code UNIQUE (code),
    CONSTRAINT fk_expense_groups_control_type_id FOREIGN KEY (control_type_id) REFERENCES expense_control_types (id)
);
CREATE INDEX idx_expense_groups_control_type_id ON expense_groups (control_type_id);

-- 비용그룹등록 [비용코드](비용 여럿을 꼬리표로 담음)
CREATE TABLE expense_group_items (
    expense_group_id bigint NOT NULL,
    expense_item_id  bigint NOT NULL,
    CONSTRAINT pk_expense_group_items PRIMARY KEY (expense_group_id, expense_item_id),
    CONSTRAINT fk_expense_group_items_group FOREIGN KEY (expense_group_id) REFERENCES expense_groups (id) ON DELETE CASCADE,
    CONSTRAINT fk_expense_group_items_item FOREIGN KEY (expense_item_id) REFERENCES expense_items (id)
);
CREATE INDEX idx_expense_group_items_item_id ON expense_group_items (expense_item_id);

