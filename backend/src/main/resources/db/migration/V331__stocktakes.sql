-- 간편 재고실사 — 원본은 간편재고조정을 하면 실사와 조정이 따로 남는다(2026-10-12 loginaa 실측).
-- 조정을 지워도 재고실사조회에 실사가 [조정전표] 빈 채로 남고, 실사는 재고실사조회 [선택삭제]로 따로 지운다.
-- 여태 우리는 간편 실사를 적지 않고 재고조정(ADJUST)을 그대로 실사로 보여 줘서, 조정을 지우면 실사도 사라졌다.

CREATE TABLE stocktakes (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     timestamp(6),
    updated_at     timestamp(6),
    stocktake_no   varchar(30)    NOT NULL UNIQUE,
    stocktake_date date           NOT NULL,
    warehouse_id   bigint         NOT NULL REFERENCES warehouses(id),
    item_id        bigint         NOT NULL REFERENCES items(id),
    actual_qty     numeric(18, 2) NOT NULL,
    employee_id    bigint,
    -- 이 실사로 맞춘 재고조정. 조정을 지우면 비고(원본 [조정전표] 빈칸), 실사는 남는다.
    adjustment_id  bigint REFERENCES stock_adjustments(id) ON DELETE SET NULL,
    created_by     varchar(50)
);
CREATE INDEX idx_stocktakes_stocktake_date ON stocktakes (stocktake_date);
CREATE INDEX idx_stocktakes_warehouse_id ON stocktakes (warehouse_id);
CREATE INDEX idx_stocktakes_item_id ON stocktakes (item_id);
CREATE INDEX idx_stocktakes_adjustment_id ON stocktakes (adjustment_id);

-- 이미 있는 간편 조정(단계별조정이 만든 것 말고)마다 실사 한 장을 남긴다 — 그래야 재고실사조회에서 예전 실사가 안 사라진다.
INSERT INTO stocktakes (created_at, updated_at, stocktake_no, stocktake_date, warehouse_id, item_id, actual_qty,
                        employee_id, adjustment_id, created_by)
SELECT a.created_at, a.updated_at, 'ST-' || substr(a.adjust_no, 4), a.adjust_date, a.warehouse_id, a.item_id, a.after_qty,
       a.employee_id, a.id, a.created_by
FROM stock_adjustments a
WHERE a.type = 'ADJUST' AND (a.reason IS NULL OR a.reason NOT LIKE '단계별조정 %');
