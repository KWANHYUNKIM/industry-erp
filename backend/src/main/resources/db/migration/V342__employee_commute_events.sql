ALTER TABLE public.employee_commutes ADD COLUMN afternoon_half boolean NOT NULL DEFAULT false;

CREATE TABLE public.employee_commute_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) without time zone,
    updated_at  timestamp(6) without time zone,
    commute_id  bigint       NOT NULL,
    kind        varchar(3)   NOT NULL,
    at          timestamp(6) without time zone NOT NULL,
    place       varchar(50),
    outside     boolean      NOT NULL DEFAULT false,
    half_day    boolean      NOT NULL DEFAULT false,
    reason      varchar(200),
    CONSTRAINT ck_employee_commute_events_kind CHECK (kind IN ('IN', 'OUT')),
    CONSTRAINT fk_employee_commute_events_commute_id FOREIGN KEY (commute_id) REFERENCES public.employee_commutes(id) ON DELETE CASCADE
);
CREATE INDEX idx_employee_commute_events_commute_id ON public.employee_commute_events (commute_id);

