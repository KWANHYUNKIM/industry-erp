-- 고정자산 증가 · 감소 전표(원본 E010611 고정자산증가 · E010612 고정자산감소). 자산 하나에 여러 건, 각각 회계전표 한 장.
-- 원본 2026-10-21 실측: 10/05 증가 10개 1,000,000 → 10/15 증가 5개 500,000 → 10/31 감소 6개 → 11/05 감소 9개 —
-- 자산 쪽 전표번호와 회계전표 번호는 따로 매긴다. 감소의 취득원가 몫은 '증가 합계 단가 × 수량', 누계는 사람이 넣는다.
CREATE TABLE fixed_asset_movements (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamp(6) without time zone,
    updated_at       timestamp(6) without time zone,
    asset_id         bigint NOT NULL CONSTRAINT fk_fixed_asset_movements_asset_id REFERENCES fixed_assets (id),
    kind             varchar(10) NOT NULL CONSTRAINT ck_fixed_asset_movements_kind CHECK (kind IN ('INCREASE', 'DECREASE')),
    slip_date        date NOT NULL,
    quantity         numeric(18, 2) NOT NULL,
    -- 증가 = 공급가액, 감소 = 취득원가 몫
    amount           numeric(18, 2) NOT NULL,
    -- 증가 = 매입 부가세, 감소 = 매각 부가세
    vat              numeric(18, 2) NOT NULL,
    -- 감소의 감가상각누계액(원본은 손으로 넣는다), 증가는 0
    accum_amount     numeric(18, 2) NOT NULL,
    sale_amount      numeric(18, 2) NOT NULL,
    disposal_type    varchar(10) CONSTRAINT ck_fixed_asset_movements_disposal_type CHECK (disposal_type IN ('SALE', 'SCRAP')),
    gain_loss        numeric(18, 2) NOT NULL,
    -- 증가 = 출금계좌, 감소 = 입금계좌
    account_id       bigint CONSTRAINT fk_fixed_asset_movements_account_id REFERENCES accounts (id),
    journal_entry_id bigint CONSTRAINT fk_fixed_asset_movements_journal_entry_id REFERENCES journal_entries (id),
    remark           varchar(200),
    created_by       varchar(50)
);
CREATE INDEX idx_fixed_asset_movements_asset_id ON fixed_asset_movements (asset_id);
CREATE INDEX idx_fixed_asset_movements_account_id ON fixed_asset_movements (account_id);
CREATE INDEX idx_fixed_asset_movements_journal_entry_id ON fixed_asset_movements (journal_entry_id);
CREATE INDEX idx_fixed_asset_movements_slip_date ON fixed_asset_movements (slip_date);

-- 자산에는 감소 합계만 들고 있는다(취득가 · 수량 · 누계는 증가 합계 · 상각 합계 그대로) — 장부가 = (취득 − 감소취득) − (누계 − 감소누계).
ALTER TABLE fixed_assets ADD COLUMN decreased_cost numeric(18, 2);
ALTER TABLE fixed_assets ADD COLUMN decreased_accum numeric(18, 2);
ALTER TABLE fixed_assets ADD COLUMN decreased_quantity numeric(18, 2);

-- 백필 1: 자산마다 증가 1건(취득 분개가 있으면 그것을 단다)
INSERT INTO fixed_asset_movements (created_at, updated_at, asset_id, kind, slip_date, quantity, amount, vat, accum_amount,
                                   sale_amount, disposal_type, gain_loss, account_id, journal_entry_id, remark, created_by)
SELECT a.created_at, a.updated_at, a.id, 'INCREASE', a.acquisition_date, a.quantity, a.acquisition_cost, a.acquisition_vat, 0,
       0, NULL, 0, a.payment_account_id,
       (SELECT je.id FROM journal_entries je WHERE je.source_type = 'ASSET_ACQUISITION' AND je.source_id = a.id),
       a.remark, a.created_by
FROM fixed_assets a ORDER BY a.id;

-- 백필 2: 처분된 자산은 감소 1건(그때까지의 누계 전부 · 처분 분개)
INSERT INTO fixed_asset_movements (created_at, updated_at, asset_id, kind, slip_date, quantity, amount, vat, accum_amount,
                                   sale_amount, disposal_type, gain_loss, account_id, journal_entry_id, remark, created_by)
SELECT a.updated_at, a.updated_at, a.id, 'DECREASE', a.disposal_date, a.quantity, a.acquisition_cost, COALESCE(a.disposal_vat, 0),
       a.accumulated_depreciation, COALESCE(a.disposal_amount, 0), COALESCE(a.disposal_type, 'SALE'),
       COALESCE(a.disposal_amount, 0) - (a.acquisition_cost - a.accumulated_depreciation), a.receipt_account_id,
       (SELECT je.id FROM journal_entries je WHERE je.source_type = 'DISPOSAL' AND je.source_id = a.id),
       a.remark, a.created_by
FROM fixed_assets a WHERE a.status = 'DISPOSED' AND a.disposal_date IS NOT NULL ORDER BY a.id;

UPDATE fixed_assets a SET decreased_cost = COALESCE(m.cost, 0), decreased_accum = COALESCE(m.accum, 0), decreased_quantity = COALESCE(m.qty, 0)
FROM (SELECT x.id, SUM(d.amount) AS cost, SUM(d.accum_amount) AS accum, SUM(d.quantity) AS qty
      FROM fixed_assets x LEFT JOIN fixed_asset_movements d ON d.asset_id = x.id AND d.kind = 'DECREASE' GROUP BY x.id) m
WHERE m.id = a.id;
UPDATE fixed_assets SET decreased_cost = 0 WHERE decreased_cost IS NULL;
UPDATE fixed_assets SET decreased_accum = 0 WHERE decreased_accum IS NULL;
UPDATE fixed_assets SET decreased_quantity = 0 WHERE decreased_quantity IS NULL;
ALTER TABLE fixed_assets ALTER COLUMN decreased_cost SET NOT NULL;
ALTER TABLE fixed_assets ALTER COLUMN decreased_accum SET NOT NULL;
ALTER TABLE fixed_assets ALTER COLUMN decreased_quantity SET NOT NULL;

-- 분개의 출처를 자산 id → 증가 · 감소 전표 id 로(자산 하나에 증가가 여러 장이라). 유니크(출처, id)가 중간에 부딪치지 않게 음수를 거친다.
UPDATE journal_entries je SET source_id = -m.id FROM fixed_asset_movements m
WHERE m.journal_entry_id = je.id AND je.source_type IN ('ASSET_ACQUISITION', 'DISPOSAL');
UPDATE journal_entries SET source_id = -source_id
WHERE source_type IN ('ASSET_ACQUISITION', 'DISPOSAL') AND source_id < 0;
