-- 업무권한(원본 Self-Customizing › 사용자관리 — 사용자등록 [권한] 탭 · 권한그룹 설정 · 권한승인대기현황 · 관리자설정).
-- 원본 정리: .claude/skills/ecount-diff/plans/데이터이관/원본-업무권한.md · 원본-업무권한-영상정리.md
--
-- 모델
--   * 마스터(관리자설정) = ADMIN 역할을 가진 사용자. 전권이고, 여러 명일 수 있다. 칸을 따로 두지 않는다 — 지금도 ADMIN 이 전권이다.
--   * 기본권한 users.base_permission: ALL(업무모든권한) / NONE(업무권한없음) / GROUP(권한그룹 = 사용자의 ADMIN 아닌 역할).
--   * 업무별 권한 work_permissions: 사용자(user_id) 또는 권한그룹(role_id) 한 쪽에 붙는다.
--       mode ALLOW(권한있음) · DENY(권한없음) · EXC_ACTION(예외(행위) — 조회는 되고 입력/수정/삭제/외부전송을 칸별로) ·
--       EXC_MENU(예외(메뉴) — menu_rules 의 'path=Y|N' 줄로 하위 메뉴마다 진입 여부).
--     사용자 줄이 있으면 그것이 기본권한(그룹)보다 우선한다(원본 '예외 설정은 업무별 권한보다 항상 우선').
--   * 권한그룹의 줄이 없는 업무 = 권한없음.
--
-- 지금 쓰는 사람의 접근을 그대로 옮기는 규칙
--   * 기존 사용자는 모두 GROUP — 지금처럼 자기 역할들의 권한을 따른다(ADMIN 은 마스터라 상관없음).
--   * 역할의 role_permissions(부여된 권한 코드) → 그 역할의 ALLOW 줄. 부여되지 않은 업무는 줄이 없다 = 권한없음.
--     지금도 부여되지 않은 업무의 화면은 메뉴 가드(canRoute)가 자물쇠로 막고 쓰기는 403 이었다. 조회 API 가 이제 같은 기준으로 막힌다
--     (다른 업무 화면에서 곁다리로 읽는 조회는 그 화면 권한으로 통과 — AuthorizationInterceptor).
--   * role_permissions 표는 지우지 않고 남긴다(더 이상 읽지 않음).
ALTER TABLE users ADD COLUMN base_permission varchar(10) NOT NULL DEFAULT 'GROUP';
ALTER TABLE users ADD CONSTRAINT ck_users_base_permission CHECK (base_permission IN ('ALL', 'NONE', 'GROUP'));

CREATE TABLE work_permissions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint,
    role_id     bigint,
    work_code   varchar(50) NOT NULL,
    mode        varchar(20) NOT NULL,
    can_create  boolean NOT NULL DEFAULT true,
    can_update  boolean NOT NULL DEFAULT true,
    can_delete  boolean NOT NULL DEFAULT true,
    can_export  boolean NOT NULL DEFAULT true,
    menu_rules  text,
    created_at  timestamp(6) without time zone,
    updated_at  timestamp(6) without time zone,
    CONSTRAINT fk_work_permissions_user_id FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_work_permissions_role_id FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
    CONSTRAINT fk_work_permissions_work_code FOREIGN KEY (work_code) REFERENCES permissions(code),
    CONSTRAINT ck_work_permissions_owner CHECK ((user_id IS NULL) <> (role_id IS NULL)),
    CONSTRAINT ck_work_permissions_mode CHECK (mode IN ('ALLOW', 'DENY', 'EXC_ACTION', 'EXC_MENU')),
    CONSTRAINT uk_work_permissions_user UNIQUE (user_id, work_code),
    CONSTRAINT uk_work_permissions_role UNIQUE (role_id, work_code)
);
-- user_id · role_id 의 FK 인덱스는 위 UNIQUE 의 앞 칸이 맡는다.
CREATE INDEX idx_work_permissions_work_code ON work_permissions (work_code);

INSERT INTO work_permissions (role_id, work_code, mode, created_at, updated_at)
SELECT rp.role_id, rp.permission_code, 'ALLOW', now(), now()
FROM role_permissions rp;

-- 권한요청(권한 없는 화면의 [권한요청]) → 권한승인대기현황
CREATE TABLE permission_requests (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id    bigint NOT NULL,
    work_code       varchar(50) NOT NULL,
    menu_path       varchar(200),
    menu_name       varchar(100),
    reason          varchar(500),
    status          varchar(10) NOT NULL,
    requested_at    timestamp(6) without time zone NOT NULL,
    processed_by_id bigint,
    processed_at    timestamp(6) without time zone,
    approve_kind    varchar(10),
    created_at      timestamp(6) without time zone,
    updated_at      timestamp(6) without time zone,
    CONSTRAINT fk_permission_requests_requester_id FOREIGN KEY (requester_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_permission_requests_processed_by_id FOREIGN KEY (processed_by_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_permission_requests_work_code FOREIGN KEY (work_code) REFERENCES permissions(code),
    CONSTRAINT ck_permission_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_permission_requests_approve_kind CHECK (approve_kind IN ('USER', 'GROUP'))
);
CREATE INDEX idx_permission_requests_requester_id ON permission_requests (requester_id);
CREATE INDEX idx_permission_requests_processed_by_id ON permission_requests (processed_by_id);
CREATE INDEX idx_permission_requests_work_code ON permission_requests (work_code);
-- 같은 사람 · 같은 업무의 대기 요청은 하나만(다시 누르면 사유 · 시각만 새로 쓴다)
CREATE UNIQUE INDEX uk_permission_requests_pending ON permission_requests (requester_id, work_code) WHERE status = 'PENDING';

