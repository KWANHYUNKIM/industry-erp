-- 항목 금액을 손으로 넣는다(2026-10-20 loginaa 실측). 항목은 화면이 정한 차례대로 lines_json 에 [{key,label,amount}] 로 둔다.
CREATE TABLE public.statement_sheets (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6) without time zone,
    updated_at   timestamp(6) without time zone,
    kind         varchar(20)  NOT NULL,
    term_no      integer      NOT NULL,
    from_ym      varchar(7)   NOT NULL,
    to_ym        varchar(7)   NOT NULL,
    settle_date  date,
    all_items    boolean      NOT NULL DEFAULT true,
    lines_json   text         NOT NULL DEFAULT '[]',
    CONSTRAINT statement_sheets_kind_check CHECK (kind IN ('CASH_FLOW', 'RETAINED_EARNINGS'))
);
CREATE INDEX idx_statement_sheets_kind ON public.statement_sheets (kind, term_no);
