-- 프로젝트계획(E040636) 원본 계획 모델 — 2026-10-14 loginaa 실측(plans/재고2/E040636.md).
-- 원본 계획은 (프로젝트, 시작일 · 완료일 · 적요) 머리 + 항목(01 판매 · 02 구매 · 03 노무비 · 04 경비)마다
-- 계획 줄(적요 · 금액 · 달별 금액) 여러 개다. 목록 [판매] … 는 줄 [금액] 의 합, 실적현황 예상금액은 달별 금액.
-- 우리는 (프로젝트, 계획연도, 네 항목 한 해 금액)이었다. 네 금액 칸(plan_revenue …)은 줄 [금액] 합으로 남겨 둔다.

-- 1) 계획의 시작일 · 완료일 — 기존 행은 계획연도 1/1 ~ 12/31
ALTER TABLE project_plans ADD COLUMN start_date date;
ALTER TABLE project_plans ADD COLUMN end_date date;
UPDATE project_plans SET start_date = make_date(plan_year, 1, 1) WHERE start_date IS NULL;
UPDATE project_plans SET end_date = make_date(plan_year, 12, 31) WHERE end_date IS NULL;
ALTER TABLE project_plans ALTER COLUMN start_date SET NOT NULL;
ALTER TABLE project_plans ALTER COLUMN end_date SET NOT NULL;

-- 2) 항목 계획 줄
CREATE TABLE project_plan_lines (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6),
    updated_at timestamp(6),
    plan_id    bigint         NOT NULL REFERENCES project_plans (id) ON DELETE CASCADE,
    item_code  varchar(2)     NOT NULL CHECK (item_code IN ('01', '02', '03', '04')),
    remark     varchar(300),
    amount     numeric(18, 2) NOT NULL DEFAULT 0
);
CREATE INDEX idx_project_plan_lines_plan_id ON project_plan_lines (plan_id);

-- 3) 줄의 달별 금액(YYYY-MM)
CREATE TABLE project_plan_line_months (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id bigint         NOT NULL REFERENCES project_plan_lines (id) ON DELETE CASCADE,
    ym      varchar(7)     NOT NULL,
    amount  numeric(18, 2) NOT NULL DEFAULT 0,
    UNIQUE (line_id, ym)
);
CREATE INDEX idx_project_plan_line_months_line_id ON project_plan_line_months (line_id);

-- 4) 기존 계획을 새 모델로 옮긴다(지우지 않는다): 0 이 아닌 항목마다 줄 하나 + 달 하나.
--    달은 지난 실적현황이 놓던 자리 — 프로젝트 시작달이 계획연도면 그 달, 아니면 그해 1월.
INSERT INTO project_plan_lines (created_at, updated_at, plan_id, item_code, remark, amount)
SELECT now(), now(), pp.id, v.code, pp.remark, v.amount
FROM project_plans pp
CROSS JOIN LATERAL (VALUES ('01', pp.plan_revenue), ('02', pp.plan_purchase),
                           ('03', pp.plan_labor), ('04', pp.plan_expense)) AS v(code, amount)
WHERE v.amount <> 0;

INSERT INTO project_plan_line_months (line_id, ym, amount)
SELECT l.id,
       CASE WHEN p.start_date IS NOT NULL AND extract(year FROM p.start_date) = pp.plan_year
            THEN to_char(p.start_date, 'YYYY-MM')
            ELSE pp.plan_year || '-01' END,
       l.amount
FROM project_plan_lines l
JOIN project_plans pp ON pp.id = l.plan_id
JOIN projects p ON p.id = pp.project_id;
