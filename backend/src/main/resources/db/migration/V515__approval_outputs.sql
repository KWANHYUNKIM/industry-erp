-- 전자결재 기안서 [결재문서] › '전표 출력물' — 원본은 판매현황 · 미판매현황 같은 출력물을 기안서에 붙인다
-- (2026-10-30 loginaa 실측: [적용] 하면 '출력물 [판매현황]2026/10/30 오전 10:27:44' 칩이 생기고, 누르면 적용할 때 찍은 사본이 뜬다).
--   mode SNAPSHOT — 적용한 때의 보고서를 얼려 둔다(html).
--   mode AUTO     — [자동갱신]: 조건(conditions)만 두고 열 때마다 다시 조회한다(원본 미실측 — 추정).
-- 기안서를 지우면(물리 삭제) 같이 지운다.
CREATE TABLE approval_outputs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL,
    sort_order  integer NOT NULL,
    menu_name   varchar(50) NOT NULL,
    applied_at  timestamp(6) without time zone NOT NULL,
    mode        varchar(20) NOT NULL,
    html        text,
    conditions  jsonb,
    CONSTRAINT fk_approval_outputs_document_id FOREIGN KEY (document_id) REFERENCES approval_documents(id) ON DELETE CASCADE,
    CONSTRAINT ck_approval_outputs_mode CHECK (mode IN ('SNAPSHOT', 'AUTO'))
);
CREATE INDEX idx_approval_outputs_document_id ON approval_outputs (document_id);
