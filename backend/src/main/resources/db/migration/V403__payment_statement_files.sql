-- 자료구분(일괄생성 · 근로소득 · 퇴직소득 · 거주자 기타소득 · 거주자 사업소득 · 비거주자 사업,기타소득 · 이자,배당소득 · 의료비명세서) ·
-- 귀속연월 · 신고일자 · 꼬리표(중도정산 포함/미포함 · 반영기준 귀속연월/지급연월 · 기타소득 포함/미포함/일부포함) ·
-- 담당자 부서명 · 성명 · 전화번호(셋 다 필수) · 제출자. 같은 자료구분 · 귀속연월은 한 줄('이미 생성된 자료입니다.').
CREATE TABLE payment_statement_files (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind           varchar(30)  NOT NULL CHECK (kind IN ('BATCH', 'LABOR', 'RETIREMENT', 'RESIDENT_OTHER',
                                                         'RESIDENT_BUSINESS', 'NONRESIDENT', 'INTEREST_DIVIDEND', 'MEDICAL')),
    attr_year      integer      NOT NULL,
    attr_month     integer      NOT NULL CHECK (attr_month BETWEEN 1 AND 12),
    report_date    date         NOT NULL,
    mid_settlement boolean      NOT NULL,
    basis          varchar(20)  NOT NULL CHECK (basis IN ('ATTRIBUTION', 'PAYMENT')),
    other_income   varchar(10)  NOT NULL CHECK (other_income IN ('INCLUDE', 'EXCLUDE', 'PARTIAL')),
    manager_dept   varchar(100) NOT NULL,
    manager_name   varchar(100) NOT NULL,
    manager_phone  varchar(50)  NOT NULL,
    submitter      varchar(10)  NOT NULL CHECK (submitter IN ('DIRECT', 'AGENT')),
    created_at     timestamp,
    updated_at     timestamp,
    CONSTRAINT uk_payment_statement_files_kind_month UNIQUE (kind, attr_year, attr_month)
);
