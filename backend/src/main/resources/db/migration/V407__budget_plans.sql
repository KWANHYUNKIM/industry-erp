-- 예산을 원본 회계 II › 예산관리(월별예산조회 E020201, 2026-10-14 loginaa 실측 — plans/회계2/E020201.md) 모양으로:
-- 기준년도 × 계정 × 부서 × 프로젝트 한 줄에 1~12월 금액. 옛 budgets(귀속월 × 계정 하나)는 옮기고 지운다.
CREATE TABLE public.budget_plans (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6) without time zone,
    updated_at    timestamp(6) without time zone,
    fiscal_year   integer       NOT NULL,
    account_id    bigint        NOT NULL,
    -- 부서 · 프로젝트가 비면 원본 '[00]기타'
    department_id bigint,
    project_id    bigint,
    remark        varchar(300),
    m01 numeric(18,2) NOT NULL DEFAULT 0,
    m02 numeric(18,2) NOT NULL DEFAULT 0,
    m03 numeric(18,2) NOT NULL DEFAULT 0,
    m04 numeric(18,2) NOT NULL DEFAULT 0,
    m05 numeric(18,2) NOT NULL DEFAULT 0,
    m06 numeric(18,2) NOT NULL DEFAULT 0,
    m07 numeric(18,2) NOT NULL DEFAULT 0,
    m08 numeric(18,2) NOT NULL DEFAULT 0,
    m09 numeric(18,2) NOT NULL DEFAULT 0,
    m10 numeric(18,2) NOT NULL DEFAULT 0,
    m11 numeric(18,2) NOT NULL DEFAULT 0,
    m12 numeric(18,2) NOT NULL DEFAULT 0,
    -- 같은 해 · 계정 · 부서 · 프로젝트는 한 줄(비어 있는 '기타' 끼리도 같다고 본다)
    CONSTRAINT uk_budget_plans_year_account_dept_project
        UNIQUE NULLS NOT DISTINCT (fiscal_year, account_id, department_id, project_id),
    CONSTRAINT fk_budget_plans_account_id FOREIGN KEY (account_id) REFERENCES public.accounts(id),
    CONSTRAINT fk_budget_plans_department_id FOREIGN KEY (department_id) REFERENCES public.departments(id),
    CONSTRAINT fk_budget_plans_project_id FOREIGN KEY (project_id) REFERENCES public.projects(id)
);
CREATE INDEX idx_budget_plans_account_id ON public.budget_plans (account_id);
CREATE INDEX idx_budget_plans_department_id ON public.budget_plans (department_id);
CREATE INDEX idx_budget_plans_project_id ON public.budget_plans (project_id);

-- 옛 예산(귀속월 × 계정)을 그 해 '기타 · 기타' 줄의 그 달 칸으로 옮긴다.
INSERT INTO public.budget_plans (created_at, updated_at, fiscal_year, account_id, remark,
                             m01, m02, m03, m04, m05, m06, m07, m08, m09, m10, m11, m12)
SELECT min(created_at), max(updated_at), substr(period, 1, 4)::integer, account_id, max(remark),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '01'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '02'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '03'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '04'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '05'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '06'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '07'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '08'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '09'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '10'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '11'), 0),
       coalesce(sum(amount) FILTER (WHERE substr(period, 6, 2) = '12'), 0)
FROM public.budgets
GROUP BY substr(period, 1, 4), account_id;

DROP TABLE public.budgets;
