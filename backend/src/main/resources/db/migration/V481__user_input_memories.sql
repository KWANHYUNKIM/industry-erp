-- 사용자별 '마지막에 쓴 값' 기억. 원본은 계정마다 서버에 남겨서 다른 PC · 브라우저에서도 같은 머리가 채워진다.
CREATE TABLE user_input_memories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    mem_key     varchar(100) NOT NULL,
    mem_value   text         NOT NULL,
    created_at  timestamp,
    updated_at  timestamp,
    CONSTRAINT uk_user_input_memories_user_key UNIQUE (user_id, mem_key)
);

CREATE INDEX idx_user_input_memories_user ON user_input_memories (user_id);
