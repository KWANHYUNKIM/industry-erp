-- 원본 재고 I · 회계 I › 기초등록 › 사원(담당)등록(E010110) — 전표의 [담당자] 마스터를 관리 › 사원등록(employees)에서 떼어 낸다.
-- 원본은 두 마스터가 따로다(H01 김기현 / 2020-003 김기현). 묶음 U(2026-10-29 사용자 결정).
CREATE TABLE sales_reps (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           varchar(50)  NOT NULL UNIQUE,
    name           varchar(100) NOT NULL,
    search_keyword varchar(100),
    remark         varchar(200),
    phone          varchar(30),
    email          varchar(100),
    extra3         varchar(100),
    extra4         varchar(100),
    extra5         varchar(100),
    extra6         varchar(100),
    active         boolean      NOT NULL DEFAULT true,
    created_at     timestamp,
    updated_at     timestamp
);

-- 지금까지 담당자로 쓰던 사원을 같은 id 로 옮긴다 — 전표의 employee_id(FK 있는 판매 · 구매 · 주문 · 견적 · 출하,
-- FK 없이 id 만 드는 작업지시서 · 생산불출 · 생산입고 · 재고조정 · 창고이동)가 값을 바꾸지 않고 그대로 이 표를 가리킨다.
INSERT INTO sales_reps (id, code, name, search_keyword, remark, phone, email, active, created_at, updated_at)
SELECT id, code, name, search_keyword, remark, phone, email, active, created_at, updated_at FROM employees;

SELECT setval(pg_get_serial_sequence('sales_reps', 'id'), coalesce((SELECT max(id) FROM sales_reps), 0) + 1, false);

