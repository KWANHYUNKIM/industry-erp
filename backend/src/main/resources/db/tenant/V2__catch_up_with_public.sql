CREATE TABLE IF NOT EXISTS chat_messages (
    id bigint NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    room_id bigint NOT NULL,
    sender_id bigint,
    content text NOT NULL,
    sent_at timestamp(6) without time zone NOT NULL
);
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
                   WHERE c.relnamespace = current_schema()::regnamespace
                     AND c.relname = 'chat_messages' AND a.attname = 'id' AND a.attidentity <> '') THEN
        ALTER TABLE chat_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME chat_messages_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
        );
    END IF;
END $$;
