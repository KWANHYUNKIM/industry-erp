-- ⚠ 이 파일은 CLAUDE.md 7.1 의 "방어 구문(IF NOT EXISTS)을 쓰지 마세요" 규칙의 <b>예외</b>다.
-- 까닭을 적어 둔다.
--
-- 이 스크립트는 이름 그대로 <b>뒤처진 테넌트를 본사에 따라붙이는</b> 것이다. 그런데 V1 baseline 은
-- 그 뒤로 갱신되어 지금은 여기서 만드는 표 열다섯 개를 이미 다 가지고 있다. 그래서
--   · 이미 있던 테넌트(co_0002)는 V2 가 예전에 돌아 표가 생겼고,
--   · <b>새로 만드는 회사</b>는 V1 이 이미 만든 표를 V2 가 또 만들려다 42P07 로 터졌다.
-- 실제로 회사 만들기가 500 으로 죽어 있었다 — relation "chat_messages" already exists.
--
-- 따라붙이는 스크립트는 <b>이미 같은 모양이면 아무 일도 안 하는 것이 맞다.</b> 그래서 여기만
-- 방어 구문을 쓴다. 새 변경은 이 파일이 아니라 V3, V4 … 로 추가하고, 거기서는 규칙대로
-- 방어 구문 없이 쓴다.

-- 테넌트 스키마를 public(본사) 과 같은 모양으로 맞춘다.
--
-- 왜 필요했나: 지금까지 스키마 변경을 db/migration 에만 넣고 db/tenant 에는 넣지 않았다.
-- 테넌트 스키마는 회사를 만들 때 V1__tenant_baseline.sql 이 한 번 실행되고 그 뒤로는 아무것도
-- 따라오지 않아서, 본사에 테이블·컬럼이 늘 때마다 테넌트만 뒤처졌다. 실제로 테이블 15개와
-- 컬럼 25개가 빠져 있었다(short_messages 통째, schedule_events.location/attendees,
-- sales_lines.lot_no 등). 테넌트 회사로 로그인해 그 화면을 열면 'column does not exist' 로
-- 터진다. ddl-auto:validate 는 기동할 때 기본 스키마만 보므로 이 어긋남을 잡지 못한다.
--
-- 앞으로: 스키마를 바꾸면 db/migration 과 db/tenant **양쪽에** 넣는다.
-- TenantMigrationRunner 가 기동할 때마다 등록된 모든 회사 스키마에 db/tenant 를 적용한다.
-- V1__tenant_baseline.sql 은 기존 테넌트에 '적용됨'으로 박혀 있으므로 절대 고치지 않는다
-- (고치면 체크섬이 어긋나 기존 테넌트의 마이그레이션이 통째로 멈춘다).
--
-- 이 파일의 DDL 은 손으로 쓰지 않고 public 스키마에서 그대로 떠 왔다.

