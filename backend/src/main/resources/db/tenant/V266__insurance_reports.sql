-- 4대보험신고(원본 N001768 · 취득 N001769 · 상실 N001770 · 피부양자 N001771): 사업장관리 + 신고 전표.
-- 신고서 파일 · EDI 전송은 만들지 않는다(모양만). 주민등록번호는 저장하지 않는다(사용자 결정 대기).
CREATE TABLE insurance_workplaces (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) without time zone,
    updated_at  timestamp(6) without time zone,
    name        varchar(100) NOT NULL,
    manage_no   varchar(11)  NOT NULL,
    phone       varchar(30),
    active      boolean      NOT NULL DEFAULT true,
    CONSTRAINT uk_insurance_workplaces_manage_no UNIQUE (manage_no)
);

CREATE TABLE insurance_reports (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at               timestamp(6) without time zone,
    updated_at               timestamp(6) without time zone,
    report_date              date         NOT NULL,
    report_seq               integer      NOT NULL,
    kind                     varchar(20)  NOT NULL,
    employee_id              bigint       NOT NULL,
    pension_workplace_id     bigint,
    health_workplace_id      bigint,
    employment_workplace_id  bigint,
    accident_workplace_id    bigint,
    pension_apply            boolean      NOT NULL DEFAULT false,
    pension_date             date,
    health_apply             boolean      NOT NULL DEFAULT false,
    health_date              date,
    employment_apply         boolean      NOT NULL DEFAULT false,
    employment_date          date,
    accident_apply           boolean      NOT NULL DEFAULT false,
    accident_date            date,
    phone                    varchar(30),
    detail                   text,
    dependents               text,
    deleted                  boolean      NOT NULL DEFAULT false,
    CONSTRAINT fk_insurance_reports_employee_id FOREIGN KEY (employee_id) REFERENCES employees(id),
    CONSTRAINT fk_insurance_reports_pension_wp FOREIGN KEY (pension_workplace_id) REFERENCES insurance_workplaces(id),
    CONSTRAINT fk_insurance_reports_health_wp FOREIGN KEY (health_workplace_id) REFERENCES insurance_workplaces(id),
    CONSTRAINT fk_insurance_reports_employment_wp FOREIGN KEY (employment_workplace_id) REFERENCES insurance_workplaces(id),
    CONSTRAINT fk_insurance_reports_accident_wp FOREIGN KEY (accident_workplace_id) REFERENCES insurance_workplaces(id),
    CONSTRAINT uk_insurance_reports_no UNIQUE (report_date, report_seq),
    CONSTRAINT ck_insurance_reports_kind CHECK (kind IN ('ACQUIRE', 'LOSS', 'DEPENDENT'))
);
CREATE INDEX idx_insurance_reports_employee_id ON insurance_reports (employee_id);
CREATE INDEX idx_insurance_reports_pension_workplace_id ON insurance_reports (pension_workplace_id);
CREATE INDEX idx_insurance_reports_health_workplace_id ON insurance_reports (health_workplace_id);
CREATE INDEX idx_insurance_reports_employment_workplace_id ON insurance_reports (employment_workplace_id);
CREATE INDEX idx_insurance_reports_accident_workplace_id ON insurance_reports (accident_workplace_id);
