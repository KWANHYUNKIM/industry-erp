-- 판매 · 구매 전표의 거래구분(일반 · 반품) 칸을 지운다 — V177(테넌트 V48)에서 만든 return_slip.
--
-- 원본 이카운트 판매입력 · 구매입력에는 거래구분 칸이 없다. 반품은 일반 전표에 음수 수량으로 적는다
-- (판매 [반품처리] = 같은 머리 · 일자 오늘 · 줄 수량/금액 음수, 2026-10-28 loginaa 실측). 사용자 결정(2026-10-28):
-- "이카운트 쪽으로 맞춰주라".
--
-- 자료는 옮길 것이 없다: return_slip = true 이던 전표(2026-10-28 본사 판매 517 · 구매 1, 회사 스키마 0)는
-- 저장할 때 이미 줄 수량 · 공급가액 · 부가세 · 머리 합계를 음수로 뒤집어 두었고(서비스가 했다), 줄이 전부 음수였다.
-- 반대로 return_slip = false 인데 줄이 전부 음수인 전표는 0 이었다. 그래서 '반품 전표 = 줄이 전부 음수' 로
-- 엔티티가 읽어도(Sales · Purchase.isReturnSlip) 모든 전표에서 예전 표시와 같고, 재고 이력 · 채권 · 회계반영은
-- 수량 · 금액만 읽으므로 아무것도 바뀌지 않는다.
ALTER TABLE sales DROP COLUMN return_slip;
ALTER TABLE purchases DROP COLUMN return_slip;
