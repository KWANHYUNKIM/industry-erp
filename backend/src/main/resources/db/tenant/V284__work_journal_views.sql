-- 업무일지 조회 기록 — 원본 E070304 '조회' 창 [R] '조회자 현황'(이름 · 최초조회일시 · 최종조회일시).
-- 글이 지워지면 기록도 같이 지운다. (journal_id, username) 유일 인덱스가 FK 컬럼 인덱스를 겸한다.
CREATE TABLE work_journal_views (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id      bigint      NOT NULL REFERENCES work_journals(id) ON DELETE CASCADE,
    username        varchar(50) NOT NULL,
    first_viewed_at timestamp(6) NOT NULL,
    last_viewed_at  timestamp(6) NOT NULL,
    CONSTRAINT uk_work_journal_views_journal_user UNIQUE (journal_id, username)
);
