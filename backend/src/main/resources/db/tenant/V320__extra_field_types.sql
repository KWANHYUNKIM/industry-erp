CREATE TABLE extra_field_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(20) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT now(),
    updated_at timestamp NOT NULL DEFAULT now()
);
CREATE TABLE extra_field_type_slots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id bigint NOT NULL REFERENCES extra_field_types (id) ON DELETE CASCADE,
    slot_no integer NOT NULL,
    enabled boolean NOT NULL DEFAULT false,
    required boolean NOT NULL DEFAULT false,
    default_value varchar(100),
    CONSTRAINT extra_field_type_slots_no_check CHECK (slot_no BETWEEN 1 AND 8),
    CONSTRAINT uq_extra_field_type_slots UNIQUE (type_id, slot_no)
);
CREATE INDEX idx_extra_field_type_slots_type_id ON extra_field_type_slots (type_id);
CREATE TABLE extra_field_type_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id bigint NOT NULL REFERENCES extra_field_types (id) ON DELETE CASCADE,
    account_id bigint NOT NULL REFERENCES accounts (id),
    CONSTRAINT uq_extra_field_type_accounts UNIQUE (type_id, account_id)
);
CREATE INDEX idx_extra_field_type_accounts_type_id ON extra_field_type_accounts (type_id);
CREATE INDEX idx_extra_field_type_accounts_account_id ON extra_field_type_accounts (account_id);
