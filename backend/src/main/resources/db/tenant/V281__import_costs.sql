CREATE TABLE import_lots (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamp(6) without time zone,
    updated_at       timestamp(6) without time zone,
    code             varchar(30)  NOT NULL,
    name             varchar(100) NOT NULL,
    partner_id       bigint       NOT NULL,
    first_trade_date date,
    remark           varchar(300),
    active           boolean      NOT NULL,
    CONSTRAINT uk_import_lots_code UNIQUE (code),
    CONSTRAINT fk_import_lots_partner_id FOREIGN KEY (partner_id) REFERENCES business_partners (id)
);
CREATE INDEX idx_import_lots_partner_id ON import_lots (partner_id);

CREATE TABLE import_cost_vouchers (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamp(6) without time zone,
    updated_at       timestamp(6) without time zone,
    voucher_date     date          NOT NULL,
    kind             varchar(20)   NOT NULL,
    lot_id           bigint        NOT NULL,
    partner_id       bigint,
    cost_item_id     bigint,
    amount           numeric(18,2) NOT NULL,
    vat              numeric(18,2) NOT NULL,
    fee              numeric(18,2) NOT NULL,
    account_id       bigint,
    bank_account_id  bigint,
    department_id    bigint,
    project_id       bigint,
    vat_type         varchar(30),
    remark           varchar(300),
    journal_entry_id bigint,
    created_by       varchar(50),
    CONSTRAINT ck_import_cost_vouchers_kind CHECK (kind IN ('BILL_RECEIPT','TAX_INVOICE','GENERAL_RECEIPT',
                                                            'TRADE_PAYMENT','BROKER_PAYMENT','TRANSFER')),
    CONSTRAINT fk_import_cost_vouchers_lot_id FOREIGN KEY (lot_id) REFERENCES import_lots (id),
    CONSTRAINT fk_import_cost_vouchers_partner_id FOREIGN KEY (partner_id) REFERENCES business_partners (id),
    CONSTRAINT fk_import_cost_vouchers_cost_item_id FOREIGN KEY (cost_item_id) REFERENCES import_cost_items (id),
    CONSTRAINT fk_import_cost_vouchers_account_id FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT fk_import_cost_vouchers_bank_account_id FOREIGN KEY (bank_account_id) REFERENCES bank_accounts (id),
    CONSTRAINT fk_import_cost_vouchers_project_id FOREIGN KEY (project_id) REFERENCES projects (id),
    -- 회계거래조회에서 그 회계전표를 지우면 수입비용 전표도 같이 사라진다
    CONSTRAINT fk_import_cost_vouchers_journal_entry_id FOREIGN KEY (journal_entry_id) REFERENCES journal_entries (id) ON DELETE CASCADE
);
CREATE INDEX idx_import_cost_vouchers_voucher_date ON import_cost_vouchers (voucher_date);
CREATE INDEX idx_import_cost_vouchers_lot_id ON import_cost_vouchers (lot_id);
CREATE INDEX idx_import_cost_vouchers_partner_id ON import_cost_vouchers (partner_id);
CREATE INDEX idx_import_cost_vouchers_cost_item_id ON import_cost_vouchers (cost_item_id);
CREATE INDEX idx_import_cost_vouchers_account_id ON import_cost_vouchers (account_id);
CREATE INDEX idx_import_cost_vouchers_bank_account_id ON import_cost_vouchers (bank_account_id);
CREATE INDEX idx_import_cost_vouchers_project_id ON import_cost_vouchers (project_id);
CREATE INDEX idx_import_cost_vouchers_journal_entry_id ON import_cost_vouchers (journal_entry_id);

ALTER TABLE journal_entries DROP CONSTRAINT ck_journal_entries_source_type;
ALTER TABLE journal_entries ADD CONSTRAINT ck_journal_entries_source_type
    CHECK (source_type IN ('SALES','PURCHASE','EXPENSE','BANK','CARD','NOTE',
                           'DEPRECIATION','DISPOSAL','VOUCHER','NONCASH','CHECK',
                           'PAYROLL','ACCOUNT_TRANSFER','CARD_PAYMENT','SETTLEMENT','MANUAL',
                           'SUBCONTRACT','DAILY_WAGE','VAT_SALES','VAT_PURCHASE','BALANCE_ADJUST','IMPORT_COST'));
